"""Tests for D1 (locate) -- the handedness triple product and the facing instrument.

The properties that matter here are mathematical, and they are what the whole D1 argument
rests on, so they are tested directly rather than through the report: a proper rotation
must leave the handedness sign alone, and a reflection must invert it. If those two ever
stopped holding, every conclusion in `docs/reviews/facing-location-2026-09-02.md` would
be void and nothing else in the repo would notice.

The report-shaped tests skip when the artefacts are absent -- `artifacts/` is gitignored
and regenerated by `tools/compare/facing_location.py`.
"""

